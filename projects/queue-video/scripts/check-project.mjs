import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const shots=JSON.parse(readFileSync('src/shots.json','utf8'));
const caps=JSON.parse(readFileSync('src/captions.json','utf8'));
const root=readFileSync('src/Root.tsx','utf8');
const sequences=[...root.matchAll(/<Series.Sequence name="(A\d+)[^"]*" durationInFrames=\{(\d+)\}/g)];
assert.equal(sequences.length,30);assert.equal(shots.length,30);assert.equal(caps.length,27);
shots.forEach((s,i)=>{assert.equal(s.id,sequences[i][1]);assert.equal(s.end-s.start,Number(sequences[i][2]));assert.equal(s.start,i?shots[i-1].end:0)});
assert.equal(shots.at(-1).end,4500);
caps.forEach(c=>{assert(c.endMs-c.startMs-150>=2400,'Caption has insufficient fully readable duration');const shot=shots.find(s=>c.startMs>=s.start/30*1000&&c.startMs<s.end/30*1000);assert.equal(c.text,shot.caption.replaceAll('／','\n'))});
const left=[1,1,1,1],right=[5,1];assert.equal(left.reduce((a,b)=>a+b),4);assert.equal(right.reduce((a,b)=>a+b),6);
const result={shots:30,frames:4500,seconds:150,captions:27,captionText:'matches source storyboard',minimumFullyReadableMs:Math.min(...caps.map(c=>c.endMs-c.startMs-150)),serviceExample:{leftSeconds:4,rightSeconds:6,heroExcluded:true},renderAndSubjectiveReview:'see status.md and delivery.json'};
writeFileSync('docs/checks.json',JSON.stringify(result,null,2)+'\n');console.log(result);
